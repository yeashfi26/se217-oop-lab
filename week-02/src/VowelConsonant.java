public class VowelConsonant {
public static void main(String[] args) {
        char ch = 'u';

        if (ch == 'a' || ch == 'e' || ch == 'i' ||
            ch == 'o' || ch == 'u') {
            Number.out.println("Vowel");
        } else {
            Number.out.println("Consonant");
        }
    }    
}
